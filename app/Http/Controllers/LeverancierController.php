<?php

namespace App\Http\Controllers;

use Illuminate\Support\Facades\DB;
use Illuminate\View\View;
use PDO;

class LeverancierController extends Controller
{
    public function index(): View
    {
        $leveranciers = $this->getLeveranciersOverzicht();

        return view('leverancier.index', [
            'leveranciers' => $leveranciers,
        ]);
    }

    public function producten(int $leverancierId): View
    {
        $leverancier = DB::table('Leverancier')
            ->where('Id', $leverancierId)
            ->first();

        if (! $leverancier) {
            abort(404, 'Leverancier niet gevonden.');
        }

        $producten = $this->getGeleverdeProducten($leverancierId);

        return view('leverancier.producten', [
            'leverancier' => $leverancier,
            'producten' => $producten,
            'heeftProducten' => count($producten) > 0,
            'melding' => count($producten) === 0
                ? 'Dit bedrijf heeft tot nu toe geen producten geleverd aan Jamin'
                : '',
        ]);
    }

    protected function getLeveranciersOverzicht(): array
    {
        $pdo = DB::connection()->getPdo();

        $statement = $pdo->prepare('CALL sp_GetLeveranciersOverzicht()');
        $statement->execute();
        $leveranciers = $statement->fetchAll(PDO::FETCH_OBJ);

        while ($statement->nextRowset()) {
            // Consume additional result sets generated by the stored procedure.
        }

        $statement->closeCursor();

        return $leveranciers;
    }

    protected function getGeleverdeProducten(int $leverancierId): array
    {
        $pdo = DB::connection()->getPdo();

        $statement = $pdo->prepare('CALL sp_GetGeleverdeProducten(?)');
        $statement->bindValue(1, $leverancierId, PDO::PARAM_INT);
        $statement->execute();
        $producten = $statement->fetchAll(PDO::FETCH_OBJ);

        while ($statement->nextRowset()) {
            // Consume additional result sets generated by the stored procedure.
        }

        $statement->closeCursor();

        return $producten;
    }
}
